export type Pt = [number, number];

/** 펜이 지나는 점. 위에서 아래로 그리는 순서대로다 */
export const PEN: Pt[] = [
  [11.6, 3.4], //     펜을 내려놓는 자리 (왼쪽 볼록한 부분 위)
  [3.6, 12.5], //  1  ↙ 왼쪽 아래로
  [19.7, 3.5], //  2  ↗ 오른쪽 위로
  [3.6, 21.2], //  3  ↙
  [25.1, 7.4], //  4  ↗
  [6.9, 28.3], //  5  ↙
  [41.9, 3.7], //  6  ↗ 오른쪽 볼록한 부분까지 길게
  [12.0, 34.4], //  7  ↙
  [48.1, 9.7], //  8  ↗
  [18.0, 39.8], //  9  ↙
  [49.2, 17.9], // 10  ↗
  [23.2, 43.6], // 11  ↙ 뾰족한 끝 왼쪽까지
  [47.6, 27], // 12  ↗ 오른쪽 위로 가장 가파르게
  [28, 47], // 13  ↙ 뾰족한 끝으로
  [42, 39], // 14  ↗ 오른쪽 아래 테두리를 덮으며 마무리
];

/** 점들을 순서대로 이어 SVG 경로 문자열로 만든다 */
export function heartPath(points: Pt[] = PEN): string {
  return points.map(([x, y], i) => `${i === 0 ? "M" : "L"}${x} ${y}`).join(" ");
}
